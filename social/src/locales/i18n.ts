const savedLanguage = storageService.getItem<string>('app_language') || 'en';

i18n.use(initReactI18next).init({
  resources,
  lng: savedLanguage,
  fallbackLng: 'en',
  interpolation: {
    escapeValue: false,
  },
});

export const changeLanguage = async (lng: string) => {
  await i18n.changeLanguage(lng);
  storageService.setItem('app_language', lng);
  const isRtl = lng === 'ar';
  if (I18nManager.isRTL !== isRtl) {
    I18nManager.allowRTL(isRtl);
    I18nManager.forceRTL(isRtl);
  }
};

export default i18n;
